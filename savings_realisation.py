#!/usr/bin/env python3
"""
Savings realisation tracker: the finance view of a cloud-cost-savings engine.

The problem this answers: an optimisation platform reports savings it has
*identified*. Finance has to answer a different question, which is how much of
that actually landed in the bill, and where the rest went.

Three gaps sit between the two numbers, and they have different owners:
  backlog   identified, never actioned            -> owned by the customer
  leakage   actioned, but the bill moved less     -> owned by the product
  drift     bill moved, then crept back up        -> owned by nobody, usually

Run:
    python3 savings_realisation.py            # writes report.md + realisation.csv
    python3 savings_realisation.py --test     # runs the self-check

Every number in the sample data is synthetic and generated by this file. It is
a worked method on invented figures, not a claim about anyone's real spend.
"""
import argparse, csv, random, sys
from collections import defaultdict

MATERIALITY_USD = 25_000      # below this a variance is not worth a sentence
MATERIALITY_PCT = 0.15        # or a 15% miss against what was identified
TOP_N = 5                     # commentary nobody reads is commentary nobody acts on


def sample_rows(seed=7):
    """Deterministic synthetic book of work: 3 clouds, 12 customers, 2 months."""
    rnd = random.Random(seed)
    clouds = ["AWS", "Azure", "GCP"]
    tiers = ["block-storage", "object-storage", "compute"]
    rows = []
    for c in range(1, 13):
        customer = f"CUST-{c:02d}"
        for month in ("2026-09", "2026-10"):
            for tier in tiers:
                cloud = clouds[(c + len(tier)) % 3]
                identified = rnd.randrange(20_000, 400_000)
                # not everything identified gets approved by the customer
                action_rate = rnd.uniform(0.45, 1.0)
                actioned = int(identified * action_rate)
                # of what is actioned, some never shows up in the bill
                capture = rnd.uniform(0.70, 1.02)
                realised = int(actioned * capture)
                rows.append({
                    "customer": customer, "month": month, "cloud": cloud,
                    "tier": tier, "identified_usd": identified,
                    "actioned_usd": actioned, "realised_usd": realised,
                })
    return rows


def enrich(rows):
    for r in rows:
        r["backlog_usd"] = r["identified_usd"] - r["actioned_usd"]
        r["leakage_usd"] = r["actioned_usd"] - r["realised_usd"]
        r["realisation_rate"] = (r["realised_usd"] / r["identified_usd"]
                                 if r["identified_usd"] else 0.0)
    return rows


def total(rows, key):
    return sum(r[key] for r in rows)


def by(rows, key):
    out = defaultdict(list)
    for r in rows:
        out[r[key]].append(r)
    return dict(out)


def rate_volume(prior, current):
    """
    Split the movement in realised savings into the two things that can cause it.

    volume: we actioned a different amount of work
    rate:   the same amount of work converted at a different rate

    Holding rate at the prior period isolates volume, and the remainder is rate.
    This is the standard FP&A decomposition; the cross term is folded into rate
    so the two parts always add back to the total, which is what matters when
    somebody asks why the number moved.
    """
    p_act, c_act = total(prior, "actioned_usd"), total(current, "actioned_usd")
    p_real, c_real = total(prior, "realised_usd"), total(current, "realised_usd")
    p_rate = p_real / p_act if p_act else 0.0
    c_rate = c_real / c_act if c_act else 0.0
    volume = (c_act - p_act) * p_rate
    rate = (c_real - p_real) - volume
    return {"total": c_real - p_real, "volume": volume, "rate": rate,
            "prior_rate": p_rate, "current_rate": c_rate}


def commentary(rows, month):
    """One sentence per variance that clears materiality, largest first."""
    lines = []
    for customer, rs in by(rows, "customer").items():
        ident, real = total(rs, "identified_usd"), total(rs, "realised_usd")
        miss = ident - real
        if miss < MATERIALITY_USD and (ident == 0 or miss / ident < MATERIALITY_PCT):
            continue
        backlog, leakage = total(rs, "backlog_usd"), total(rs, "leakage_usd")
        driver = "backlog" if backlog > leakage else "leakage"
        share = (backlog if driver == "backlog" else leakage) / miss if miss else 0
        worst = max(rs, key=lambda r: r["backlog_usd"] + r["leakage_usd"])
        lines.append((miss,
            f"- **{customer}** ({month}): identified ${ident:,.0f}, realised "
            f"${real:,.0f}, a ${miss:,.0f} shortfall at "
            f"{real / ident:.0%} realisation. {share:.0%} of the gap is {driver}"
            f"{' awaiting customer approval' if driver == 'backlog' else ' where actions did not move the bill'}"
            f", concentrated in {worst['tier']} on {worst['cloud']}."))
    lines.sort(key=lambda x: -x[0])
    head = [l for _, l in lines[:TOP_N]]
    tail = lines[TOP_N:]
    if tail:
        head.append(f"- {len(tail)} further accounts fall below the line, "
                    f"${sum(m for m, _ in tail):,.0f} in aggregate. Listed in "
                    f"`realisation.csv`, not repeated here.")
    return head


def build_report(rows):
    rows = enrich(rows)
    months = sorted({r["month"] for r in rows})
    prior, current = [r for r in rows if r["month"] == months[0]], \
                     [r for r in rows if r["month"] == months[-1]]
    rv = rate_volume(prior, current)

    out = []
    out.append("# Savings realisation, identified versus landed\n")
    out.append("Synthetic data, generated by `savings_realisation.py`. "
               "The method is the point, not the figures.\n")
    out.append(f"## Headline, {months[-1]}\n")
    ident, act, real = (total(current, "identified_usd"),
                        total(current, "actioned_usd"),
                        total(current, "realised_usd"))
    out.append(f"| Measure | USD | % of identified |")
    out.append("|---|---:|---:|")
    out.append(f"| Identified | {ident:,.0f} | 100% |")
    out.append(f"| Actioned | {act:,.0f} | {act/ident:.0%} |")
    out.append(f"| Realised in the bill | {real:,.0f} | {real/ident:.0%} |")
    out.append(f"| Backlog, awaiting approval | {total(current,'backlog_usd'):,.0f} | {total(current,'backlog_usd')/ident:.0%} |")
    out.append(f"| Leakage, actioned but not landed | {total(current,'leakage_usd'):,.0f} | {total(current,'leakage_usd')/ident:.0%} |")

    out.append(f"\n## Why realised savings moved, {months[0]} to {months[-1]}\n")
    out.append(f"- Total movement: ${rv['total']:,.0f}")
    out.append(f"- Volume, more or less work actioned: ${rv['volume']:,.0f}")
    out.append(f"- Rate, conversion of actioned into landed: ${rv['rate']:,.0f} "
               f"({rv['prior_rate']:.0%} to {rv['current_rate']:.0%})")
    out.append("\nSplitting it this way separates a sales question from a product "
               "question. Volume moves when customers approve more work. Rate moves "
               "when the actions stop converting, and that is the one worth a "
               "standup.\n")

    out.append(f"## Variances worth a sentence, {months[-1]}\n")
    out.append(f"Materiality: ${MATERIALITY_USD:,} or {MATERIALITY_PCT:.0%} of identified.\n")
    lines = commentary(current, months[-1])
    out.extend(lines if lines else ["- Nothing clears materiality this month."])

    out.append("\n## By cloud\n")
    out.append("| Cloud | Identified | Realised | Realisation |")
    out.append("|---|---:|---:|---:|")
    for cloud, rs in sorted(by(current, "cloud").items()):
        i, r = total(rs, "identified_usd"), total(rs, "realised_usd")
        out.append(f"| {cloud} | {i:,.0f} | {r:,.0f} | {r/i:.0%} |")
    return "\n".join(out) + "\n", rows


def self_check():
    rows = enrich(sample_rows())
    for r in rows:
        assert r["identified_usd"] == r["backlog_usd"] + r["actioned_usd"], "backlog must close"
        assert r["actioned_usd"] == r["leakage_usd"] + r["realised_usd"], "leakage must close"
    months = sorted({r["month"] for r in rows})
    prior = [r for r in rows if r["month"] == months[0]]
    current = [r for r in rows if r["month"] == months[-1]]
    rv = rate_volume(prior, current)
    assert abs(rv["volume"] + rv["rate"] - rv["total"]) < 1e-6, "decomposition must add back"
    flat = rate_volume(prior, prior)
    assert abs(flat["total"]) < 1e-9 and abs(flat["rate"]) < 1e-9, "no movement, no variance"
    c1, c2 = commentary(current, months[-1]), commentary(current, months[-1])
    assert c1 == c2, "commentary must be deterministic across calls"
    misses = []
    for cust, rs in by(current, "customer").items():
        misses.append((cust, total(rs, "identified_usd") - total(rs, "realised_usd")))
    named = [l.split("**")[1] for l in c1 if "**" in l]
    ranked = [c for c, _ in sorted(misses, key=lambda x: -x[1])][:len(named)]
    assert named == ranked, "commentary must be ordered by shortfall, largest first"
    assert len(named) <= TOP_N, "commentary must stay capped"
    print("self-check passed:",
          "backlog and leakage reconcile, decomposition adds back, zero case is zero")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--test", action="store_true")
    a = ap.parse_args()
    if a.test:
        self_check(); sys.exit(0)
    md, rows = build_report(sample_rows())
    open("report.md", "w").write(md)
    cols = ["customer", "month", "cloud", "tier", "identified_usd", "actioned_usd",
            "realised_usd", "backlog_usd", "leakage_usd", "realisation_rate"]
    with open("realisation.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols); w.writeheader()
        for r in rows:
            w.writerow({k: r[k] for k in cols})
    print("wrote report.md and realisation.csv")
